// Helper parser to build full array grids from layout templates
function parseLevel(template) {
    const tileRows = template.map.length;
    const tileCols = template.map[0].length;
    const grid = [];

    for (let r = 0; r < tileRows; r++) {
        grid[r] = new Array(tileCols);
        for (let c = 0; c < tileCols; c++) {
            const char = template.map[r][c];
            let val = 0; // default empty space

            if (char === '#') val = 1;      // Ground
            else if (char === 'b') val = 2; // Brick
            else if (char === '?') val = 3; // Question coin
            else if (char === 'M') val = 4; // Question power-up
            else if (char === 'S') val = 5; // Solid block
            else if (char === '[') val = 6; // Pipe top-left
            else if (char === ']') val = 7; // Pipe top-right
            else if (char === '(') val = 8; // Pipe body-left
            else if (char === ')') val = 9; // Pipe body-right
            else if (char === 'l') val = 10; // Lava
            else if (char === 'w') val = 11; // Water

            grid[r][c] = val;
        }
    }

    // Deep clone template and assign parsed grid
    return {
        name: template.name,
        type: template.type,
        skyColor: template.skyColor,
        timeLimit: template.timeLimit,
        startPos: { ...template.startPos },
        flagPos: template.flagPos,
        grid: grid,
        cols: tileCols,
        rows: tileRows,
        enemies: template.enemies.map(e => ({ ...e })),
        firebars: template.firebars ? template.firebars.map(f => ({ ...f })) : [],
        scenery: template.scenery.map(s => ({ ...s }))
    };
}

window.parseLevel = parseLevel;
window.LEVEL_TEMPLATES = LEVEL_TEMPLATES;
